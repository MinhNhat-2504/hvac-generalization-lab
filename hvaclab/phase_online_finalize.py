"""Idempotent local report/paper finalization after the phase study completes."""
import argparse
import json
from pathlib import Path
import shutil
import subprocess
import time
from hvaclab.coverage import digest,write_json
from hvaclab.pi_calibration import RunLock

ROOT=Path('experiments/runs/phase_online_short')


def finalize():
    from hvaclab.phase_online_review import main as review
    review();result=json.loads((ROOT/'verified_review.json').read_text())
    fingerprint=digest(ROOT/'protocol.json');marker='% phase_online_verified_'+fingerprint
    paper=Path('reports/paper/updates_2026_10_27.tex');source=paper.read_text(encoding='utf-8')
    means=result['overall'];baseline=means['phase_ctrl']
    if marker not in source:
        lines=['',marker,'\\subsection{Verified phase-specific feedback results, 5 November}',
            'All eight 2016-step rollouts completed and passed frozen-input, identity,',
            'phase-reward conservation and prior-control reproduction checks. The',
            'shadow reproduced all 4032 V10 commands exactly. Learning remained active',
            'when feedback was masked; actual applied corrections were counted separately',
            'from proposed corrections. Each run started from fresh learner state.',
            '\\begin{center}\\small','\\begin{tabular}{lrrrrr}\\toprule',
            'Arm & Loss & Comfort & Energy & Carbon & Change \\\\\\midrule']
        for arm,row in means.items():
            label=arm.replace('_','\\_')
            change=100*(row['loss']/baseline['loss']-1)
            lines.append(f"\\texttt{{{label}}} & {row['loss']:.8f} & {row['comfort']:.8f} & {row['energy']:.8f} & {row['carbon']:.8f} & {change:+.3f}\\% \\\\")
        lines+=['\\bottomrule\\end{tabular}\\end{center}',
            'All-window feedback minus V10, cost booked by decision-time phase:',
            '\\begin{center}\\small','\\begin{tabular}{lrrrr}\\toprule',
            'Phase & Loss difference & Comfort difference & Energy difference & Carbon difference \\\\\\midrule']
        for phase,row in result['delta_vs_control']['phase_all'].items():
            label=phase.replace('_','\\_')
            lines.append(f"\\texttt{{{label}}} & {row['loss']:+.8f} & {row['comfort']:+.8f} & {row['energy']:+.8f} & {row['carbon']:+.8f} \\\\")
        lines+=['\\bottomrule\\end{tabular}\\end{center}']
        for arm,gate in result['gates'].items():
            label=arm.replace('_','\\_')
            lines.append(f"The fixed short gate for \\texttt{{{label}}} "+('passed.' if gate['passes_short_gate'] else 'failed.')+
                         (' Corrections were active in both cases.' if gate['active_in_each_case'] else ' At least one case had no applied corrections.'))
        lines+=['These are short selected dev prefixes, not full-scenario or hidden-test',
            'scores. Effects carry across phases through thermal mass, PI history and',
            'online learning. The all-arm residual relative to prestart and occupied',
            'treatments also includes scheduled-empty compensation and cannot identify',
            'a pure interaction. Cost booking alone does not prove direct phase causality.',
            'No full sweep or submission notebook is generated by this analysis.',
            'Earlier measurements and rejected branches remain preserved.']
        paper.write_text(source+'\n'.join(lines)+'\n',encoding='utf-8')
    compiler=shutil.which('pdflatex')
    if not compiler:raise RuntimeError('pdflatex unavailable')
    build=(ROOT/'paper_build').resolve();build.mkdir(parents=True,exist_ok=True)
    with (ROOT/'paper_final.log').open('w') as log:
        for _ in range(2):subprocess.run([compiler,'-no-shell-escape','-interaction=nonstopmode','-halt-on-error','-output-directory',str(build),'main.tex'],cwd='reports/paper',stdout=log,stderr=subprocess.STDOUT,check=True)
    target=Path('reports/paper/main.pdf');temp=target.with_suffix('.pdf.phase.tmp');shutil.copyfile(build/'main.pdf',temp);temp.replace(target)
    context=Path('PROJECT_CONTEXT.md');old=context.read_text(encoding='utf-8')
    context_marker='phase_online_final_'+fingerprint
    if context_marker not in old:
        lines=['',f'- 2026-11-05: phase diagnosis completed8/8, verified exact4032 V10 commands,',
            '  old control/all totals and per-phase conservation. No notebook/full sweep.']
        for arm,row in means.items():lines.append(f"  {arm}: loss{row['loss']:.10f}, comfort{row['comfort']:.10f}, energy{row['energy']:.10f}, carbon{row['carbon']:.10f}.")
        lines += ['  Gates: '+json.dumps(result['gates'],sort_keys=True),
            '  Report reports/PHASE_ONLINE_SHORT_REVIEW.md, verified_review.json and',
            '  paper PDF finalized locally. Phase booking includes carryover; do not',
            '  mistake scheduled_empty+interaction residual for a pure factorial effect.',
            '  '+context_marker]
        context.write_text(old+'\n'.join(lines)+'\n',encoding='utf-8')
    write_json(ROOT/'finalization.json',dict(status='complete',protocol_sha256=fingerprint,
        report_sha256=digest('reports/PHASE_ONLINE_SHORT_REVIEW.md'),paper_sha256=digest(target),
        paper_source_sha256=digest(paper),gates=result['gates']))
    print('LOCAL_PAPER_AND_REVIEW_FINALIZED',flush=True)


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--watch',action='store_true');args=parser.parse_args()
    ROOT.mkdir(parents=True,exist_ok=True)
    with RunLock(ROOT/'finalizer.lock'):
        if args.watch:
            while True:
                try:state=json.loads((ROOT/'status.json').read_text())
                except (OSError,ValueError):state={}
                if state.get('status')=='complete':break
                time.sleep(15)
        elif json.loads((ROOT/'status.json').read_text()).get('status')!='complete':raise RuntimeError('study not complete')
        finalize()


if __name__=='__main__':main()
